// are derived from the script's own glyphs rather than hand-written 2x.
const DAKUTEN = { ga: "ka", gi: "ki", gu: "ku", ge: "ke", go: "ko",
  za: "sa", ji: "shi", zu: "su", ze: "se", zo: "so",
  da: "ta", de: "te", do: "to",
  ba: "ha", bi: "hi", bu: "fu", be: "he", bo: "ho" };
const HANDAKUTEN = { pa: "ha", pi: "hi", pu: "fu", pe: "he", po: "ho" };
const COMBO_KEYS = ["kya","kyu","kyo","sha","shu","sho","cha","chu","cho","nya","nyu","nyo",
  "hya","hyu","hyo","mya","myu","myo","rya","ryu","ryo","gya","gyu","gyo","ja","ju","jo",
  "bya","byu","byo","pya","pyu","pyo"];

const buildMnemonics = (base, map) => {
  const m = { ...base };
  Object.entries(DAKUTEN).forEach(([k, b]) => { m[k] = `${map[b]} + two dashes, buzzed — '${k}'`; });
  Object.entries(HANDAKUTEN).forEach(([k, b]) => { m[k] = `${map[b]} + a circle, popped — '${k}'`; });
  COMBO_KEYS.forEach((k) => { m[k] = `${map[k][0]} + small ${map[k][1]} — '${k}'`; });
  return m;
};

