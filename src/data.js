const LIKES_IDX = 4;

const NUM_KANA = ["", "いち", "に", "さん", "よん", "ご", "ろく", "なな", "はち", "きゅう"];
const NUM_ROMA = ["", "ichi", "ni", "san", "yon", "go", "roku", "nana", "hachi", "kyuu"];

// 1-99 as "...さい", with the standard sound changes (いっさい, はっさい, じゅっさい).
function ageWords(n) {
  if (!n || n < 1 || n > 99) return null;
  const tens = Math.floor(n / 10), units = n % 10;
  let kana = "", roma = "";
  if (tens) { kana += (tens > 1 ? NUM_KANA[tens] : "") + "じゅう"; roma += (tens > 1 ? NUM_ROMA[tens] : "") + "juu"; }
  if (units) { kana += NUM_KANA[units]; roma += NUM_ROMA[units]; }
  if (units === 1) { kana = kana.slice(0, -2) + "いっ"; roma = roma.slice(0, -4) + "is"; }
  else if (units === 8) { kana = kana.slice(0, -2) + "はっ"; roma = roma.slice(0, -5) + "has"; }
  else if (!units && tens) { kana = kana.slice(0, -3) + "じゅっ"; roma = roma.slice(0, -3) + "jus"; }
  return { kana: kana + "さい", roma: roma + "sai" };
}

function ageFromDob(dob) {
  const d = new Date(dob);
  if (isNaN(d)) return null;
  const now = new Date();
  let a = now.getFullYear() - d.getFullYear();
  const m = now.getMonth() - d.getMonth();
  if (m < 0 || (m === 0 && now.getDate() < d.getDate())) a--;
  return a;
}

// The About me unit reflects the learner's onboarding answers when available.
export function aboutMeSentences() {
  const p = loadProfile();
  if (!p || p.skipped) return SENTENCES[0];
  const out = [
    { jp: "わたしはげんきです", romaji: "watashi wa genki desu", en: "I am well", parts: seg("わたし=watashi=I / は=wa=(topic) / げんき=genki=well / です=desu=(am)") },
    { jp: "にほんごをべんきょうします", romaji: "nihongo o benkyou shimasu", en: "I study Japanese", parts: seg("にほんご=nihongo=Japanese / を=o=(obj) / べんきょうします=benkyou shimasu=study") },
  ];
  // Dynamic chunks (name/age/country) carry the learner's own word, so the parts
  // are built directly rather than through seg()'s "=" / "/" mini-syntax.
  if (p.name) out.push({ jp: `わたしのなまえは${p.name}です`, romaji: `watashi no namae wa ${p.name} desu`, en: `My name is ${p.name}`, parts: [
    { jp: "わたしの", romaji: "watashi no", en: "my" }, { jp: "なまえ", romaji: "namae", en: "name" },
    { jp: "は", romaji: "wa", en: "(topic)" }, { jp: p.name, romaji: p.name, en: p.name }, { jp: "です", romaji: "desu", en: "is" } ] });
  const age = p.dob ? ageFromDob(p.dob) : null;
  const aw = ageWords(age);
  if (aw) out.push({ jp: `わたしは${aw.kana}です`, romaji: `watashi wa ${aw.roma} desu`, en: `I am ${age} years old`, parts: [
    { jp: "わたし", romaji: "watashi", en: "I" }, { jp: "は", romaji: "wa", en: "(topic)" },
    { jp: aw.kana, romaji: aw.roma, en: `${age} years old` }, { jp: "です", romaji: "desu", en: "am" } ] });
  const c = p.country && COUNTRIES[p.country];
  if (c) out.push({ jp: `${c.kana}からきました`, romaji: `${c.roma} kara kimashita`, en: `I'm from ${c.en}`, parts: [
    { jp: c.kana, romaji: c.roma, en: c.en }, { jp: "から", romaji: "kara", en: "from" }, { jp: "きました", romaji: "kimashita", en: "came" } ] });
  if (p.pets === "cat") out.push({ jp: "ねこをかっています", romaji: "neko o katte imasu", en: "I have a cat", parts: seg("ねこ=neko=cat / を=o=(obj) / かっています=katte imasu=have") });
  else if (p.pets === "dog") out.push({ jp: "いぬをかっています", romaji: "inu o katte imasu", en: "I have a dog", parts: seg("いぬ=inu=dog / を=o=(obj) / かっています=katte imasu=have") });
  else if (p.pets === "both") out.push({ jp: "ねこといぬをかっています", romaji: "neko to inu o katte imasu", en: "I have a cat and a dog", parts: seg("ねこ=neko=cat / と=to=and / いぬ=inu=dog / を=o=(obj) / かっています=katte imasu=have") });
  else if (p.pets === "none") out.push({ jp: "ペットはいません", romaji: "petto wa imasen", en: "I don't have pets", parts: seg("ペット=petto=pets / は=wa=(topic) / いません=imasen=don't have") });
  if (p.occupation === "study") out.push({ jp: "わたしはがくせいです", romaji: "watashi wa gakusei desu", en: "I am a student", parts: seg("わたし=watashi=I / は=wa=(topic) / がくせい=gakusei=student / です=desu=(am)") });
  else if (p.occupation === "work") out.push({ jp: "はたらいています", romaji: "hataraite imasu", en: "I work", parts: seg("はたらいています=hataraite imasu=work") });
  // pad to 25 with general About me lines the learner hasn't already got
  for (const s of SENTENCES[0]) {
    if (out.length >= 25) break;
    // the learner's own name already led the unit — never fall back to "…Tanaka"
    if (p.name && s.romaji === "watashi no namae wa tanaka desu") continue;
    if (!out.some((o) => o.romaji === s.romaji)) out.push(s);
  }
  return out;
}

// The Likes unit leads with the learner's chosen hobbies (multi-select).
export function likesSentences() {
  const p = loadProfile();
  const base = SENTENCES[LIKES_IDX];
  const picks = p && !p.skipped && Array.isArray(p.hobbies) ? p.hobbies : [];
  const mine = picks.map((h) => HOBBIES[h]).filter(Boolean)
    .map((h) => ({ jp: `${h.kana}がすきです`, romaji: `${h.roma} ga suki desu`, en: `I like ${h.en}`, parts: [
      { jp: h.kana, romaji: h.roma, en: h.en }, { jp: "が", romaji: "ga", en: "(subj)" },
      { jp: "すき", romaji: "suki", en: "like" }, { jp: "です", romaji: "desu", en: "(is)" } ] }));
  const seen = new Set(mine.map((m) => m.romaji));
  return [...mine, ...base.filter((s) => !seen.has(s.romaji))];
}

